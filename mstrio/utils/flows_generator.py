class InvalidInput(ValueError):
    """Exception raised for invalid input in the flow generator."""


def all_keys_present(entry: AnyEntry, keys: list[str]) -> bool:
    return all(key in entry for key in keys)


def validate_variable_reference(reference: Any) -> None:
    if not isinstance(reference, str):
        raise InvalidInput(f"Variable source should be a string, is: {reference}.")

    try:
        source, output = reference.split(".", 1)
    except ValueError:
        raise InvalidInput(
            f"Variable source should be in format 'key.ref', is: {reference}."
        )

    is_flow_var = source == "flow_var" and re.match(REGEX_PATTERN, output)
    is_step_ref = re.match(REGEX_PATTERN, source) and output in ("stdout", "return")

    if not is_flow_var and not is_step_ref:
        raise InvalidInput(
            "Variable source should be either reference to Flow variable in "
            "format 'flow_var.var_name' or reference to previous step output "
            "in format 'step_id.stdout' or 'step_id.return', "
            f"is: {reference}."
        )


def validate_conditional_branches(entry: AnyEntry) -> None:
    for key in ["on_fail", "on_success"]:
        if key not in entry:
            continue

        if not isinstance(steps := entry[key], list):
            raise InvalidInput(
                f"Conditional branch '{key}' should be a list of valid steps "
                "when provided."
            )

        [
            validate_any_step_entry(step, prev)
            for step, prev in list_with_prev_ref(steps, first_prev=entry)
        ]


_found_objects = []


def validate_object_entry(entry: AnyEntry) -> bool:
    try:
        ret = isinstance(entry, dict) and bool(
            re.match(REGEX_PATTERN, entry.get("id", ""))
            and re.match(REGEX_PATTERN, entry.get("project_id", ""))
        )
    except TypeError:
        return False
    else:
        if ret:
            _found_objects.append(
                {"id": entry.get("id"), "project_id": entry.get("project_id")}
            )

    return ret


def validate_script_step_entry(entry: AnyEntry) -> None:
    if not all_keys_present(entry, ["object"]) or not validate_object_entry(
        entry["object"]
    ):
        raise InvalidInput(f"Script Entry has invalid format: {entry}.")

    if "step_id" in entry and (
        entry["step_id"] == "flow_var" or not re.match(REGEX_PATTERN, entry["step_id"])
    ):
        raise InvalidInput(
            f"If provided, `step_id` should match pattern `{REGEX_PATTERN}` and "
            "not be equal to \"flow_var\", "
            f"is: {entry['step_id']}."
        )

    if "variables" in entry:
        if not isinstance(vars := entry["variables"], dict):
            raise InvalidInput(
                f"`variables` key should contain a dictionary if provided, is: {vars}."
            )

        for var_source in vars.values():
            if var_source == "default":
                continue

            validate_variable_reference(var_source)

    validate_conditional_branches(entry)


def validate_sleep_step_entry(entry: AnyEntry) -> None:
    try:
        if not all_keys_present(entry, ["duration"]) or int(entry["duration"]) <= 0:
            raise ValueError()
    except (ValueError, KeyError):
        raise InvalidInput(f"Sleep Entry has invalid format: {entry}.")


def validate_parallel_step_entry(entry: AnyEntry) -> None:
    if not all_keys_present(entry, ["branches"]) or not isinstance(
        branches := entry["branches"], list
    ):
        raise InvalidInput(f"Parallel Entry has invalid format: {entry}.")

    for branch in branches:  # noqa
        if not all_keys_present(branch, ["steps"]) or not isinstance(
            steps := branch["steps"], list
        ):
            raise InvalidInput(
                f"Branch in Parallel Entry has invalid format: {branch}."
            )

        [
            validate_any_step_entry(step, prev)
            for step, prev in list_with_prev_ref(steps, first_prev=entry)
        ]

    timeout_seconds = entry.get("timeout_seconds", DEFAULT_PARALLEL_TIMEOUT_SECONDS)
    if type(timeout_seconds) is not int or timeout_seconds <= 0:
        raise InvalidInput(
            "Parallel Entry `timeout_seconds` should be a positive integer "
            f"when provided, is: {timeout_seconds}."
        )

    validate_conditional_branches(entry)


def validate_weekday_condition_entry(entry: AnyEntry) -> None:
    values = entry.get("value")
    if (
        not isinstance(values, list)
        or not values
        or any(type(value) is not int or value not in range(7) for value in values)
    ):
        raise InvalidInput(
            "Weekday Condition `value` should be a non-empty list of integers "
            "between 0 and 6."
        )

    if "timezone" not in entry:
        return

    timezone = entry["timezone"]
    if not isinstance(timezone, str):
        raise InvalidInput("Weekday Condition `timezone` should be an IANA string.")

    try:
        ZoneInfo(timezone)
    except (ValueError, ZoneInfoNotFoundError):
        raise InvalidInput(f"Weekday Condition has invalid IANA timezone: {timezone}.")


COMPARISON_OPERATORS = {
    "equals",
    "not_equals",
    "contains",
    "begins_with",
    "ends_with",
    "greater_than",
    "greater_than_or_equal",
    "less_than",
    "less_than_or_equal",
}

ORDERING_COMPARISON_OPERATORS = {
    "greater_than",
    "greater_than_or_equal",
    "less_than",
    "less_than_or_equal",
}


def parse_numeric_comparison_constant(value: Any, side: str) -> int | float:
    if isinstance(value, str):
        try:
            value = try_str_to_num(value)
        except OverflowError:
            pass

    if type(value) is int or (type(value) is float and isfinite(value)):
        return value

    raise InvalidInput(
        f"Comparison Condition ordering operator requires numeric constant "
        f"`{side}`, is: {value!r}."
    )


def validate_comparison_operand_entry(entry: Any, side: str) -> None:
    if not isinstance(entry, dict) or "type" not in entry:
        raise InvalidInput(f"Comparison Condition `{side}` should be a typed operand.")

    match entry["type"]:
        case "variable":
            if "name" not in entry:
                raise InvalidInput(
                    f"Comparison Condition variable `{side}` should contain `name`."
                )
            validate_variable_reference(entry["name"])
        case "constant":
            if "value" not in entry:
                raise InvalidInput(
                    f"Comparison Condition constant `{side}` should contain `value`."
                )

            value = entry["value"]
            is_valid_number = type(value) in (int, float) and (
                type(value) is int or isfinite(value)
            )
            if not isinstance(value, str) and not is_valid_number:
                raise InvalidInput(
                    "Comparison Condition constants should be strings or finite "
                    f"numbers, is: {value}."
                )

            if isinstance(value, str) and any(char in value for char in ">~"):
                raise InvalidInput(
                    "Comparison Condition string constants cannot contain "
                    "characters '>' or '~'."
                )
        case other:
            raise InvalidInput(
                f"Unsupported Comparison Condition operand type: '{other}'."
            )


def validate_comparison_condition_entry(entry: AnyEntry) -> None:
    if not all_keys_present(entry, ["operator", "left", "right"]):
        raise InvalidInput(
            "Comparison Condition should contain `operator`, `left` and `right`."
        )

    operator = entry["operator"]
    if not isinstance(operator, str) or operator not in COMPARISON_OPERATORS:
        raise InvalidInput(f"Unsupported Comparison Condition operator: '{operator}'.")

    validate_comparison_operand_entry(entry["left"], "left")
    validate_comparison_operand_entry(entry["right"], "right")

    if operator in ORDERING_COMPARISON_OPERATORS:
        for side in ("left", "right"):
            operand = entry[side]
            if operand["type"] == "constant":
                parse_numeric_comparison_constant(operand["value"], side)


def validate_condition_entry(entry: Any) -> None:
    if not isinstance(entry, dict) or "type" not in entry:
        raise InvalidInput("Decision Entry `condition` should be a typed dictionary.")

    match entry["type"]:
        case "weekday":
            validate_weekday_condition_entry(entry)
        case "comparison":
            validate_comparison_condition_entry(entry)
        case other:
            raise InvalidInput(f"Unsupported Decision Condition type: '{other}'.")


def validate_decision_step_entry(entry: AnyEntry) -> None:
    if "condition" not in entry:
        raise InvalidInput("Decision Entry should contain `condition`.")

    validate_condition_entry(entry["condition"])
    validate_conditional_branches(entry)


def validate_exit_step_entry(entry: AnyEntry, prev_entry: AnyEntry | None) -> None:
    if "message" in entry:
        if not isinstance(entry["message"], str):
            raise InvalidInput("Exit Entry `message` should be a string.")
    else:
        previous_step_provides_error = (
            prev_entry
            and prev_entry["type"] in ("script", "parallel")
            and "on_fail" in prev_entry
            and prev_entry["on_fail"]
            and prev_entry["on_fail"][0] is entry
        )

        if not previous_step_provides_error:
            # Those are the scenarios that may happen and are invalid:
            #   - there is no previous step
            #   - previous step does not expose an execution error
            #   - this exit step is not the first entry in `on_fail`
            raise InvalidInput(
                "Exit Entry without custom message can only be used directly "
                "in a Script or Parallel Entry `on_fail` conditional."
            )


def validate_any_step_entry(entry: AnyEntry, prev_entry: AnyEntry | None) -> None:
    if not all_keys_present(entry, ["type", "unique_id"]):
        raise InvalidInput("Step entry does not contain `type` or `unique_id` keys.")

    if not isinstance(entry["unique_id"], str):
        raise InvalidInput("`unique_id` should be a string.")

    match entry["type"]:
        case "script":
            return validate_script_step_entry(entry)
        case "sleep":
            return validate_sleep_step_entry(entry)
        case "parallel":
            return validate_parallel_step_entry(entry)
        case "noop":
            return
        case "decision":
            return validate_decision_step_entry(entry)
        case "exit":
            return validate_exit_step_entry(entry, prev_entry)
        case other:
            raise InvalidInput(f"Unknown type of step: '{other}'.")


def validate_input_yaml_structure(parsed_input_yaml: AnyEntry) -> None:
    """Validate if the structure of the input yaml is correct and contains all
    required data.

    Raises:
        InvalidInput: when the structure of the input yaml is invalid or some
            required data is missing. Otherwise passes through without errors.
    """

    _found_objects.clear()

    # general shape
    if not isinstance(parsed_input_yaml, dict) or not all_keys_present(
        parsed_input_yaml, ["version", "dependencies", "connection", "steps"]
    ):
        raise InvalidInput(
            "Input yaml should be a dictionary with required keys: "
            "version, dependencies, connection and steps."
        )

    # setup data
    ver = parsed_input_yaml["version"]
    if not isinstance(ver, int):
        raise InvalidInput(f"Version should be an integer, is {type(ver)}.")

    if ver > GENERATOR_VERSION:
        raise InvalidInput(
            f"Input data comes from plugin with later version ({ver}) "
            f"than the generator ({GENERATOR_VERSION}). "
            "The generator cannot handle this input."
        )

    deps = parsed_input_yaml["dependencies"]
    if not isinstance(deps, list) or not all(validate_object_entry(d) for d in deps):
        raise InvalidInput("Some dependency entries are not in the required format.")

    conn = parsed_input_yaml["connection"]
    if conn != "get_connection":
        conn_params = get_args_from_func(Connection)

        if not isinstance(conn, dict) or not all(
            # TODO: better validate the value reference
            key in conn_params and isinstance(val, str) and val.startswith("flow_var.")
            for key, val in conn.items()
        ):
            raise InvalidInput(
                "Connection data is not in the required format. Either some "
                "keys are not valid `Connection` initialization keys or some "
                "values are not in proper format `flow_var.<var_name>`."
            )

    # steps data
    steps = parsed_input_yaml["steps"]
    if not isinstance(steps, list):
        raise InvalidInput(f"Steps should be a list of valid steps, is {steps}")

    [validate_any_step_entry(step, prev) for step, prev in list_with_prev_ref(steps)]

    deps_objs = {(v["id"], v["project_id"]) for v in deps}
    found_objs = {(v["id"], v["project_id"]) for v in _found_objects}
    if not all(found in deps_objs for found in found_objs):
        raise InvalidInput(
            "Not all used scripts added to dependencies. "
            "Scripts not in dependencies (<script-id>, <project-id>): "
            f"{(found_objs - deps_objs)}"
        )


