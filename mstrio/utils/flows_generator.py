def list_with_prev_ref(
    lst: list[Any], first_prev: AnyEntry | None = None
) -> Sequence[tuple[Any, Any | None]]:
    """Returns a zip-like object where `lst` entry is converted to tuple
    `(<elem>, <prev-elem-if-any>)`

    Arguments:
        lst (list): A list of elements to be paired with their previous
            elements.
        first_prev (AnyEntry | None, optional): The value to be paired with the
            first element of the list. Defaults to None. Useful when previous
            element is outside of the `lst` list.

    Returns:
        Sequence[tuple[Any, Any | None]]: An iterable of tuples where each tuple
            contains an element from the list and its previous element (or
            `first_prev` for the first element).
    """
    if not lst:
        return zip([], [])
    return zip(lst, [first_prev] + lst[:-1], strict=True)


